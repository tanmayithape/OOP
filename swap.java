package swaping;

public class swap {
	 public static void main(String[] args) {
		int a=11;
		int b=12;
		int temp=a;
		a=b;
		b=temp;
		
		System.out.println("Swaping of two number :");
		System.out.println("---------------------");
		System.out.println(a);
		System.out.println("---------------------");
		System.out.print(b);
			
	}
	}



